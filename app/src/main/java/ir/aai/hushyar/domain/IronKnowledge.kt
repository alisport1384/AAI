    /** جستجوی سریع خانواده با نام فارسی/انگلیسی */
    fun byName(name: String): IronCategory? {
        val n = Text.normalize(name).lowercase()
        return categories.firstOrNull {
            Text.normalize(it.fa).contains(n) || Text.normalize(it.en).lowercase().contains(n) || it.id == n
        }
    }

    /** تولید KnowledgeItemهای قابل فهم برای Qwen: چانک ~450 توکن، با منبع */
    fun toKnowledgeItems(clock: Long = System.currentTimeMillis()): List<KnowledgeItem> {
        val out = mutableListOf<KnowledgeItem>()
        for (cat in categories) {
            fun add(claim: String, layer: String, tags: List<String> = emptyList()) {
                // هر ادعا یک KnowledgeItem جدا — مدل Qwen از همین جمله‌ها یاد می‌گیرد
                out += KnowledgeItem(
                    id = ir.aai.hushyar.core.Ids.hash("iron:${cat.id}:$layer:${claim.take(40)}"),
                    topic = "آهن‌آلات ${cat.fa}",
                    question = when (layer) {
                        "basics" -> "${cat.fa} چیست"
                        "specs" -> "${cat.fa} مشخصات فنی"
                        "usage" -> "${cat.fa} کاربرد"
                        "trade" -> "${cat.fa} نحوه معامله"
                        "tax" -> "${cat.fa} مالیات و ارزش افزوده"
                        else -> cat.fa
                    },
                    claim = claim,
                    category = "iron",
                    attribute = cat.fa,
                    url = "asset://iron_knowledge/${cat.id}",
                    domain = "ironpin",
                    confidence = 0.92,
                    createdAt = clock,
                    lastVerifiedAt = clock,
                    ttlDays = 180,
                    sourceCount = 1,
                    layer = layer,
                    tags = tags + listOf(cat.id, cat.fa)
                )
            }
            add("${cat.fa} (${cat.en}): ${cat.intro}", "basics")
            add("شکل ${cat.fa}: ${cat.shape}", "specs", listOf("شکل"))
            add("جنس ${cat.fa}: ${cat.material}. گریدها: ${cat.grades.joinToString("، ")}", "specs", listOf("جنس", "گرید"))
            add("ساخت ${cat.fa}: ${cat.manufacturing}", "specs", listOf("ساخت"))
            add("ابعاد ${cat.fa}: ${cat.dimensions}", "specs", listOf("ابعاد"))
            add("واحدهای فروش ${cat.fa}: ${cat.units.joinToString("، ")} — انواع معامله: ${cat.dealTypes.joinToString("، ")}", "trade", listOf("واحد", "معامله"))
            add("کاربرد ${cat.fa}: ${cat.usages.joinToString("، ")}", "usage", listOf("کاربرد"))
            add("مالیات ${cat.fa}: ${cat.taxNotes}", "tax", listOf("مالیات"))
            cat.uniqueFeatures.forEach { add("ویژگی خاص ${cat.fa}: $it", "specs", listOf("ویژگی")) }
            add("محاسبه ${cat.fa}: ${cat.calculation}", "specs", listOf("فرمول", "محاسبه"))
            cat.warnings.forEach { add("هشدار ${cat.fa}: $it", "basics", listOf("هشدار")) }
        }
        // دانش عمومی تکمیلی
        val general = listOf(
            "چگالی فولاد کربنی 7850 kg/m³ است؛ مبنای تمام وزن‌های نظری همین عدد است. برای استنلس/آلومینیوم فرق می‌کند." to "basics",
            "ارزش‌افزوده آهن تا 1404 ده درصد است (شش درصد مالیات + چهار درصد عوارض). نرخ هر سال را از سامانه مالیات چک کن." to "tax",
            "حمل، انبارداری، اجاره و دستمزد اگر فاکتور رسمی داشته باشند هزینه قابل قبول مالیاتی‌اند (مواد 147 و 148)." to "tax",
            "وزن نظری ماشین‌حساب فقط برآورد است؛ ملاک تسویه باسکول یا وزن اعلامی کارخانه روی شاخه/برگ/رول است." to "basics",
            "انباردار کالا را امانی نگه می‌دارد (درآمدش اجرت انبار است)، بازرگان مالک کالاست (سود بازرگانی)." to "trade",
            "فاکتور رسمی باید سایز، گرید، طول، وزن، نوع معامله (نقد/اعتباری) و شناسه کالا را داشته باشد." to "trade"
        )
        for ((claim, layer) in general) {
            out += KnowledgeItem(
                id = ir.aai.hushyar.core.Ids.hash("iron:general:$layer:${claim.take(40)}"),
                topic = "آهن‌آلات عمومی",
                question = "آهن‌آلات $layer چیست",
                claim = claim,
                category = "iron",
                attribute = "عمومی",
                url = "asset://iron_knowledge/general",
                domain = "ironpin",
                confidence = 0.9,
                createdAt = clock,
                lastVerifiedAt = clock,
                ttlDays = 180,
                sourceCount = 1,
                layer = layer,
                tags = listOf("عمومی")
            )
        }
        return out
    }

    /** خلاصه برای نمایش در تب دانش */
